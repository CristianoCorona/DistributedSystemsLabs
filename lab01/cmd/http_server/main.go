// Command http_server is a concurrent HTTP/1.0 file server built on TCP sockets.
//
// Usage:
//
//	http_server <port>
//
// It serves and stores files in ./data, relative to the working directory.
package main

import (
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/CristianoCorona/DistributedSystemsLabs/lab01/internal/app"
	"github.com/CristianoCorona/DistributedSystemsLabs/lab01/internal/filestore"
	"github.com/CristianoCorona/DistributedSystemsLabs/lab01/internal/server"
)

// docRoot is the directory from which files are served and in which they are stored.
// It is relative to the working directory of the process.
const docRoot = "./data"

// main checks the arguments, prepares the document root and wires the layers together:
// the server (transport) calls the app (protocol), which uses the file store (domain).
func main() {
	// Validation of the port (argument)
	if len(os.Args) != 2 {
		log.Fatal("Usage: ", os.Args[0], " <port>") // logs the error and exits with a non-zero status code
	}
	port := os.Args[1]

	// Create the document root if it does not exist yet.
	if err := os.MkdirAll(docRoot, 0o755); err != nil {
		log.Fatal("Cannot create document root: ", err)
	}
	removeTempFiles(docRoot)

	// The app answers each request using a file store rooted at docRoot.
	application := app.New(filestore.New(docRoot))
	srv := server.New(":"+port, 10, application.Route, 5)
	log.Fatal(srv.Serve())
}

// removeTempFiles deletes the temporary upload files left in root by a previous
// run that was stopped during a POST. os.CreateTemp(dir, "tmp-*") replaces the
// "*" with a random decimal number, so only names of the form "tmp-<digits>"
// are removed: a client file such as "tmp-notes.txt" is left alone.
// Subdirectories of root are not scanned.
func removeTempFiles(root string) {
	matches, err := filepath.Glob(filepath.Join(root, "tmp-*"))
	if err != nil {
		log.Println("Cannot list temporary files:", err)
		return
	}
	removed := 0
	for _, path := range matches {
		suffix := strings.TrimPrefix(filepath.Base(path), "tmp-")
		if suffix == "" || strings.Trim(suffix, "0123456789") != "" {
			continue // not a name generated by os.CreateTemp
		}
		if info, err := os.Lstat(path); err != nil || !info.Mode().IsRegular() {
			continue
		}
		if err := os.Remove(path); err != nil {
			log.Println("Cannot remove temporary file:", err)
			continue
		}
		removed++
	}
	log.Printf("Removed %d leftover temporary file(s) from %s", removed, root)
}
