// Package filestore is the service layer: it maps URL paths to files under a root directory,
// reads them and replaces them atomically. It knows nothing about HTTP: callers translate
// its errors (ErrNotFound, ErrBadExtension) into status codes.
package filestore

import (
	"errors"
	"io"
	"log"
	"os"
	"path/filepath"
	"strings"
)

var (
	// ErrNotFound is returned when a requested file does not exist.
	ErrNotFound = errors.New("file not found")
	// ErrBadExtension is returned when a requested file has an unsupported extension.
	ErrBadExtension = errors.New("unsupported file extension")
)

// mimeTypes maps each servable extension to its Content-Type.
var mimeTypes = map[string]string{
	".html": "text/html",
	".txt":  "text/plain",
	".gif":  "image/gif",
	".jpeg": "image/jpeg",
	".jpg":  "image/jpeg",
	".css":  "text/css",
}

// tempPattern is the name pattern of the temporary files written by Put.
// os.CreateTemp replaces the "*" with a random decimal number. The name has no
// servable extension, so a GET can never return a half-written upload.
const tempPattern = "tmp-*"

// Store serves and stores files under a root directory.
type Store struct {
	root string
}

// Open returns a Store that serves files under root. It creates root (mode 0755) if it
// does not exist yet, so a fresh clone works without manual setup, and removes the
// temporary files that a previous run left behind.
func Open(root string) (*Store, error) {
	if err := os.MkdirAll(root, 0o755); err != nil {
		return nil, err
	}
	removeTempFiles(root)
	return &Store{root: root}, nil
}

// removeTempFiles deletes the temporary upload files left in root by a previous
// run that was stopped during a POST: deferred cleanup does not run when the process
// is killed. Only names of the form "tmp-<digits>", the ones os.CreateTemp produces
// from tempPattern, are removed: a client file such as "tmp-notes.txt" is left alone.
// Subdirectories of root are not scanned.
func removeTempFiles(root string) {
	matches, err := filepath.Glob(filepath.Join(root, tempPattern))
	if err != nil {
		log.Println("Cannot list temporary files:", err)
		return
	}
	prefix := strings.TrimSuffix(tempPattern, "*")
	removed := 0
	for _, path := range matches {
		suffix := strings.TrimPrefix(filepath.Base(path), prefix)
		if suffix == "" || strings.Trim(suffix, "0123456789") != "" {
			continue // not a name generated by os.CreateTemp
		}
		if info, err := os.Lstat(path); err != nil || !info.Mode().IsRegular() {
			continue
		}
		if err := os.Remove(path); err != nil {
			log.Println("Cannot remove temporary file:", err)
			continue
		}
		removed++
	}
	log.Printf("Removed %d leftover temporary file(s) from %s", removed, root)
}

// resolve cleans name, checks its extension and returns the path on disk
// together with the Content-Type.
func (s *Store) resolve(name string) (path, contentType string, err error) {
	// extension -> content type. If not found, return ErrBadExtension
	clean := filepath.Clean("/" + name)                                // ensure the path is clean and starts with a slash
	contentType, ok := mimeTypes[strings.ToLower(filepath.Ext(clean))] // case-insensitive extension matching
	if !ok {
		return "", "", ErrBadExtension
	}
	return filepath.Join(s.root, clean), contentType, nil // return the full path to the file and its content type
}

// Get opens the file at name and returns its content as a stream, together with its size
// and its Content-Type. The caller must close body.
//
// The file is not loaded into memory: the caller copies it to the client piece by piece.
// This is still atomic with respect to Put, because Put never writes into a visible file:
// it renames a new file over the old name. The descriptor opened here keeps pointing to the
// inode it was opened on, so a concurrent rename does not change what this reader sees, and
// the kernel frees the old inode only after this descriptor is closed. The size returned by
// Stat therefore matches the bytes the reader will get.
func (s *Store) Get(name string) (body io.ReadCloser, size int64, contentType string, err error) {
	path, contentType, err := s.resolve(name) // resolve the file path and content type

	if err != nil {
		return nil, 0, "", err // return the error if resolution failed
	}

	// Open the file. If it does not exist, return ErrNotFound.
	f, err := os.Open(path)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			// The requested file does not exist; return ErrNotFound
			return nil, 0, "", ErrNotFound
		}
		// Some other error occurred while opening the file; return generic error
		return nil, 0, "", err
	}

	// Stat the open descriptor, not the path: the path may already point to a newer
	// version, while the descriptor is the version that will be sent.
	info, err := f.Stat()
	if err != nil {
		f.Close()
		return nil, 0, "", err
	}
	// On Linux a directory can be opened like a file. A directory named, for example,
	// "photos.jpg" is not a file the client can download, so it is reported as missing.
	if info.IsDir() {
		f.Close()
		return nil, 0, "", ErrNotFound
	}
	return f, info.Size(), contentType, nil
}

// Put atomically replaces the file at name with the content of body. Concurrent readers see either the old or the new version, never a mix.
func (s *Store) Put(name string, body io.Reader) error {
	path, _, err := s.resolve(name) // resolve the file path

	if err != nil {
		return err // return the error if resolution failed
	}

	// Create a temporary file in the same directory to avoid partial writes and handle concurrent access.
	tmp, err := os.CreateTemp(filepath.Dir(path), tempPattern) // same dir of the final file. Thanks to its name without a servable extension, the file will not be served by any GET (until renamed).
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name()) // ensure the temporary file is removed after the operation
	defer tmp.Close()           // safety net (for error paths); a second Close is harmless, but necessary in case of early returns.

	// Copy the content from the provided body to the temporary file.
	_, err = io.Copy(tmp, body)
	if err != nil {
		return err
	}

	if err := tmp.Chmod(0o644); err != nil { // set the  permissions to be readable by everyone and writable by the owner.
		return err
	}

	// Durability: Write only hands the data to the kernel's page cache. Sync forces it to
	// disk, so that after a crash or power loss the renamed file is not empty or truncated.
	// It must happen before the rename: otherwise the new name could become visible while
	// its content is still only in memory.
	if err := tmp.Sync(); err != nil {
		return err
	}

	if err := tmp.Close(); err != nil { // ensure the temporary file is closed before renaming it
		return err
	}

	return os.Rename(tmp.Name(), path) // atomically replace the old file with the new one
}
